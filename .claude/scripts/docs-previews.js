#!/usr/bin/env node
'use strict';

/**
 * docs-previews.js — /autoconfig Step 6: show this project's real CLAUDE.md, MEMORY.md and
 * settings.json in the docs page's file previews.
 *
 * Writes .claude/docs/autoconfig.previews.js and NEVER touches autoconfig.docs.html. The page
 * loads the previews file with its own <script src> and swaps the values into fileContents.
 *
 * Why a separate file: Step 6 used to have the model splice the text into the page's one big
 * <script> by hand. On the CRLF docs file a hand-written indexOf('---\n\n') returned -1, the
 * splice ran from offset 4, and ~1,500 lines including the opening <script> were deleted — the
 * page rendered as raw JS text (2026-10-01). With the previews in their own file, the worst a
 * bad write can do is fail that one script; the page still runs and shows its placeholders.
 * Values are JSON-encoded, so there is no escaping to get wrong.
 *
 * Usage (from the project root):
 *     node .claude/scripts/docs-previews.js [--memory <path-to-MEMORY.md>]
 * Exit 0 = written (or no docs installed), 1 = refused; nothing is written on 1.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const GLOBAL = 'CCA_PROJECT_PREVIEWS';
const HEADER = '// Generated by /autoconfig (.claude/scripts/docs-previews.js) — regenerate, don\'t edit.\n' +
  '// Safe to delete: the docs page falls back to its placeholder previews.\n';

// Claude Code's project-dir encoding: every non-alphanumeric char becomes '-'
// (C:\CODE\my-project → C--CODE-my-project).
function defaultMemoryPath(projectDir) {
  const encoded = path.resolve(projectDir).replace(/[^a-zA-Z0-9]/g, '-');
  return path.join(os.homedir(), '.claude', 'projects', encoded, 'memory', 'MEMORY.md');
}

function readIfExists(file) {
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trimEnd() : null;
}

// { 'claude-md': text, 'memory-md': text, settings: text } for every source that exists.
// Keys are the docs page's fileContents keys.
function collectPreviews(projectDir, memoryPath) {
  const sources = {
    'claude-md': path.join(projectDir, 'CLAUDE.md'),
    'memory-md': memoryPath,
    settings: path.join(projectDir, '.claude', 'settings.json'),
  };
  const previews = {};
  for (const [key, file] of Object.entries(sources)) {
    const text = readIfExists(file);
    if (text !== null) previews[key] = text;
  }
  return previews;
}

function renderPreviewsFile(previews) {
  return HEADER + 'window.' + GLOBAL + ' = ' + JSON.stringify(previews, null, 2) + ';\n';
}

// Run the file the way the page will, and require it to yield exactly `previews`.
function verifyPreviewsFile(text, previews) {
  const win = {};
  new Function('window', text)(win);
  if (JSON.stringify(win[GLOBAL]) !== JSON.stringify(previews)) {
    throw new Error('previews file does not round-trip');
  }
}

function writeAtomic(file, content) {
  const tmp = file + '.tmp-' + process.pid;
  fs.writeFileSync(tmp, content);
  fs.renameSync(tmp, file);
}

function parseArgs(argv) {
  const i = argv.indexOf('--memory');
  return { memory: i !== -1 ? argv[i + 1] : null };
}

function main() {
  const projectDir = process.cwd();
  const docsDir = path.join(projectDir, '.claude', 'docs');
  if (!fs.existsSync(path.join(docsDir, 'autoconfig.docs.html'))) {
    console.log('No .claude/docs/autoconfig.docs.html — nothing to update.');
    return 0;
  }
  const memoryPath = parseArgs(process.argv.slice(2)).memory || defaultMemoryPath(projectDir);
  const previews = collectPreviews(projectDir, memoryPath);
  try {
    const text = renderPreviewsFile(previews);
    verifyPreviewsFile(text, previews);
    writeAtomic(path.join(docsDir, 'autoconfig.previews.js'), text);
  } catch (e) {
    console.error('docs-previews: nothing written — ' + e.message);
    return 1;
  }
  console.log('Docs previews updated: ' + (Object.keys(previews).join(', ') || 'none'));
  return 0;
}

if (require.main === module) process.exit(main());

module.exports = { collectPreviews, renderPreviewsFile, verifyPreviewsFile, defaultMemoryPath, GLOBAL };
