/**
 * Box Alignment Tests
 *
 * Validates the READY boxes cli.js actually RENDERS. Since clean-code substep 3.2 the boxes
 * are built at runtime by boxLine()/printReadyBox() inside main() — there are no box literals
 * in the source to regex-extract — so this suite runs the real CLI twice (fresh project →
 * READY TO CONFIGURE, configured project → READY TO UPDATE), captures stdout, and asserts
 * every rendered box line has the same visible width and correct borders.
 *
 * Standalone whole-run pass/fail structure (see test/_harness.js header); it borrows only
 * makeClaudeShim from the harness so `claude --version` resolves without a real install.
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const { makeClaudeShim } = require('./_harness');

const CLI_PATH = path.join(__dirname, '..', 'bin', 'cli.js');

// The boxes are ║ + 44 content chars + ║ (CLAUDE.md "Box Drawing Guidelines").
const EXPECTED_WIDTH = 46;

// Strip ANSI escape codes to get visual character count
const stripAnsi = (str) => str.replace(/\x1b\[[0-9;]*m/g, '');

// Drive the full interactive path (no --bootstrap): ENTER is piped to stdin so the run sails
// through the prompt; the launched `claude` resolves to the PATH shim, so it exits instantly.
function runInteractive(projectDir, shimDir) {
  const env = { ...process.env, CLAUDECODE: '' };
  const pathKey = Object.keys(env).find(k => k.toLowerCase() === 'path') || 'PATH';
  env[pathKey] = shimDir + path.delimiter + (env[pathKey] || '');
  return execFileSync('node', [CLI_PATH], {
    cwd: projectDir,
    encoding: 'utf8',
    input: '\n',
    stdio: ['pipe', 'pipe', 'pipe'],
    env,
    timeout: 120000
  });
}

// Render both boxes for real and collect every output line containing box-drawing chars.
function extractBoxLines() {
  const shimDir = makeClaudeShim();
  const fresh = fs.mkdtempSync(path.join(os.tmpdir(), 'cca-box-fresh-'));
  const upgrade = fs.mkdtempSync(path.join(os.tmpdir(), 'cca-box-upgrade-'));
  // The autoconfig marker makes isUpgrade true → the READY TO UPDATE box renders.
  fs.writeFileSync(path.join(upgrade, 'CLAUDE.md'),
    '<!-- AUTO-GENERATED BY /autoconfig -->\n# Project\n');
  try {
    const out = runInteractive(fresh, shimDir) + runInteractive(upgrade, shimDir);
    return out.split(/\r?\n/).filter(line => /[╔╗╚╝║═]/.test(line));
  } finally {
    for (const dir of [shimDir, fresh, upgrade]) {
      try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) { /* best effort */ }
    }
  }
}

// Test: All box lines should have the same visual width
function testBoxAlignment(lines) {
  if (lines.length === 0) {
    console.error('FAIL: No box lines rendered by cli.js');
    process.exit(1);
  }

  console.log(`Found ${lines.length} rendered box lines to validate\n`);

  const widths = lines.map(line => {
    const stripped = stripAnsi(line);
    return { line: stripped, width: stripped.length };
  });

  let allPass = true;

  widths.forEach((item, index) => {
    const indicator = item.width === EXPECTED_WIDTH ? '✓' : '✗';

    console.log(`${indicator} Line ${index + 1}: width=${item.width} (expected ${EXPECTED_WIDTH})`);
    console.log(`  "${item.line}"`);

    if (item.width !== EXPECTED_WIDTH) {
      allPass = false;
    }
  });

  console.log();

  if (allPass) {
    console.log(`SUCCESS: All ${lines.length} box lines are aligned at ${EXPECTED_WIDTH} characters`);
    return true;
  } else {
    console.error(`FAILURE: Box lines have inconsistent widths`);
    return false;
  }
}

// Test: Box structure validation (supports multiple boxes)
function testBoxStructure(lines) {
  console.log('\nValidating box structure...\n');

  let allPass = true;

  // Split lines into individual boxes (each starts with ╔ and ends with ╚)
  const boxes = [];
  let currentBox = [];
  for (const line of lines) {
    const stripped = stripAnsi(line);
    if (stripped.startsWith('╔')) {
      currentBox = [line];
    } else {
      currentBox.push(line);
    }
    if (stripped.startsWith('╚')) {
      boxes.push(currentBox);
      currentBox = [];
    }
  }

  console.log(`Found ${boxes.length} box(es)\n`);

  // Guard against a vacuous pass: the fresh run renders READY TO CONFIGURE and the upgrade
  // run renders READY TO UPDATE, so anything under two boxes means a run lost its box.
  if (boxes.length < 2) {
    console.error(`✗ Expected at least 2 rendered boxes, found ${boxes.length}`);
    return false;
  }

  for (let b = 0; b < boxes.length; b++) {
    const box = boxes[b];
    const label = `Box ${b + 1}`;

    // First line should start with ╔ and end with ╗
    const firstStripped = stripAnsi(box[0]);
    if (!firstStripped.startsWith('╔') || !firstStripped.endsWith('╗')) {
      console.log(`✗ ${label}: Top border should be ╔...╗`);
      allPass = false;
    } else {
      console.log(`✓ ${label}: Top border correct (╔...╗)`);
    }

    // Last line should start with ╚ and end with ╝
    const lastStripped = stripAnsi(box[box.length - 1]);
    if (!lastStripped.startsWith('╚') || !lastStripped.endsWith('╝')) {
      console.log(`✗ ${label}: Bottom border should be ╚...╝`);
      allPass = false;
    } else {
      console.log(`✓ ${label}: Bottom border correct (╚...╝)`);
    }

    // Middle lines should start and end with ║
    let middlePass = true;
    for (let i = 1; i < box.length - 1; i++) {
      const stripped = stripAnsi(box[i]);
      if (!stripped.startsWith('║') || !stripped.endsWith('║')) {
        console.log(`✗ ${label}: Line ${i + 1} should start and end with ║`);
        allPass = false;
        middlePass = false;
      }
    }
    if (middlePass) {
      console.log(`✓ ${label}: All middle lines have correct borders (║...║)`);
    }
  }

  if (allPass) {
    console.log('\nSUCCESS: Box structure is valid');
  } else {
    console.error('\nFAILURE: Box structure is invalid');
  }

  return allPass;
}

// Run all tests
console.log('='.repeat(60));
console.log('BOX ALIGNMENT TESTS');
console.log('='.repeat(60));
console.log();

const boxLines = extractBoxLines();
const alignmentPass = testBoxAlignment(boxLines);
const structurePass = testBoxStructure(boxLines);

console.log();
console.log('='.repeat(60));

if (alignmentPass && structurePass) {
  console.log('ALL TESTS PASSED');
  process.exit(0);
} else {
  console.log('TESTS FAILED');
  process.exit(1);
}
